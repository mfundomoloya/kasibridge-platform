CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    amount NUMERIC(15, 2) NOT NULL,

    channel VARCHAR(20) NOT NULL,

    currency VARCHAR(3) NOT NULL,

    customer_name VARCHAR(120),

    customer_phone VARCHAR(30),

    description VARCHAR(255),

    notes VARCHAR(500),

    occurred_at TIMESTAMP(6) WITHOUT TIME ZONE
        NOT NULL,

    payment_method VARCHAR(20) NOT NULL,

    recorded_at TIMESTAMP(6) WITHOUT TIME ZONE
        NOT NULL,

    reference_number VARCHAR(30) NOT NULL,

    status VARCHAR(20) NOT NULL,

    trader_id BIGINT NOT NULL,

    type VARCHAR(20) NOT NULL,

    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,

    version BIGINT,

    CONSTRAINT uk_transactions_reference_number
        UNIQUE (reference_number),

    CONSTRAINT ck_transactions_channel
        CHECK (
            channel IN (
                'WEB',
                'WHATSAPP'
            )
        ),

    CONSTRAINT ck_transactions_currency
        CHECK (
            currency = 'ZAR'
        ),

    CONSTRAINT ck_transactions_payment_method
        CHECK (
            payment_method IN (
                'CASH',
                'EFT',
                'QR',
                'WHATSAPP'
            )
        ),

    CONSTRAINT ck_transactions_status
        CHECK (
            status IN (
                'PENDING',
                'COMPLETED',
                'CANCELLED',
                'FLAGGED'
            )
        ),

    CONSTRAINT ck_transactions_type
        CHECK (
            type IN (
                'SALE',
                'EXPENSE',
                'REFUND'
            )
        )
);

CREATE INDEX idx_transaction_trader_id
    ON transactions (trader_id);

CREATE INDEX idx_transaction_trader_occurred
    ON transactions (
        trader_id,
        occurred_at
    );

CREATE INDEX idx_transaction_trader_type_status
    ON transactions (
        trader_id,
        type,
        status
    );

CREATE INDEX idx_transaction_trader_channel
    ON transactions (
        trader_id,
        channel
    );

CREATE INDEX idx_transaction_occurred_at
    ON transactions (occurred_at);

CREATE INDEX idx_transaction_recorded_at
    ON transactions (recorded_at);

CREATE INDEX idx_transaction_status
    ON transactions (status);
