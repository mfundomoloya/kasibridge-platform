CREATE SCHEMA IF NOT EXISTS fraud;

CREATE TABLE fraud.fraud_assessments (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY
                                             PRIMARY KEY,

                                         assessment_reference VARCHAR(40)
                                             NOT NULL,

                                         invoice_reference VARCHAR(100)
                                             NOT NULL,

                                         supplier_id VARCHAR(100),

                                         department_id VARCHAR(100),

                                         invoice_amount NUMERIC(19, 2)
                                             NOT NULL,

                                         supplier_country VARCHAR(3),

                                         region VARCHAR(100),

                                         classification VARCHAR(20)
                                             NOT NULL,

                                         risk_level VARCHAR(20)
                                             NOT NULL,

                                         risk_probability NUMERIC(10, 8)
                                             NOT NULL,

                                         decision_threshold NUMERIC(10, 8)
                                             NOT NULL,

                                         recommended_action VARCHAR(40)
                                             NOT NULL,

                                         model_name VARCHAR(100)
                                             NOT NULL,

                                         model_version VARCHAR(100)
                                             NOT NULL,

                                         experiment VARCHAR(100)
                                             NOT NULL,

                                         detection_source VARCHAR(30)
                                             NOT NULL,

                                         model_sha256 VARCHAR(64)
                                             NOT NULL,

                                         feature_snapshot_json TEXT
                                             NOT NULL,

                                         feature_snapshot_sha256 VARCHAR(64)
                                             NOT NULL,

                                         review_status VARCHAR(30)
                                             NOT NULL,

                                         reviewed_by VARCHAR(100),

                                         review_notes VARCHAR(1000),

                                         reviewed_at TIMESTAMP,

                                         assessed_at TIMESTAMP
                                             NOT NULL,

                                         created_at TIMESTAMP
                                             NOT NULL,

                                         updated_at TIMESTAMP,

                                         version BIGINT
                                             NOT NULL DEFAULT 0,

                                         CONSTRAINT uk_fraud_assessment_reference
                                             UNIQUE (assessment_reference),

                                         CONSTRAINT uk_fraud_assessment_invoice_model
                                             UNIQUE (
                                                     invoice_reference,
                                                     model_version
                                                 ),

                                         CONSTRAINT ck_fraud_assessment_probability
                                             CHECK (
                                                 risk_probability >= 0
                                                     AND risk_probability <= 1
                                                 ),

                                         CONSTRAINT ck_fraud_assessment_threshold
                                             CHECK (
                                                 decision_threshold >= 0
                                                     AND decision_threshold <= 1
                                                 ),

                                         CONSTRAINT ck_fraud_assessment_classification
                                             CHECK (
                                                 classification IN (
                                                                    'LEGITIMATE',
                                                                    'HIGH_RISK'
                                                     )
                                                 ),

                                         CONSTRAINT ck_fraud_assessment_risk_level
                                             CHECK (
                                                 risk_level IN (
                                                                'LOW',
                                                                'MEDIUM',
                                                                'HIGH',
                                                                'CRITICAL'
                                                     )
                                                 ),

                                         CONSTRAINT ck_fraud_assessment_review_status
                                             CHECK (
                                                 review_status IN (
                                                                   'PENDING_REVIEW',
                                                                   'AUTO_CLEARED',
                                                                   'CONFIRMED_FRAUD',
                                                                   'FALSE_POSITIVE',
                                                                   'ESCALATED'
                                                     )
                                                 ),

                                         CONSTRAINT ck_fraud_assessment_detection_source
                                             CHECK (
                                                 detection_source IN (
                                                                      'SUPERVISED_MODEL',
                                                                      'DETERMINISTIC_RULE',
                                                                      'HYBRID'
                                                     )
                                                 ),

                                         CONSTRAINT ck_fraud_assessment_action
                                             CHECK (
                                                 recommended_action IN (
                                                                        'ALLOW_WITH_MONITORING',
                                                                        'REQUIRE_REVIEW',
                                                                        'HOLD_PAYMENT_AND_REVIEW',
                                                                        'BLOCK_AND_ESCALATE'
                                                     )
                                                 ),

                                         CONSTRAINT ck_fraud_assessment_model_sha256
                                             CHECK (
                                                 model_sha256 ~ '^[a-f0-9]{64}$'
),

    CONSTRAINT ck_fraud_assessment_snapshot_sha256
        CHECK (
            feature_snapshot_sha256
                ~ '^[a-f0-9]{64}$'
        )
);

CREATE INDEX idx_fraud_assessment_invoice
    ON fraud.fraud_assessments (
                                invoice_reference
        );

CREATE INDEX idx_fraud_assessment_supplier
    ON fraud.fraud_assessments (
                                supplier_id
        );

CREATE INDEX idx_fraud_assessment_department
    ON fraud.fraud_assessments (
                                department_id
        );

CREATE INDEX idx_fraud_assessment_risk
    ON fraud.fraud_assessments (
                                risk_level
        );

CREATE INDEX idx_fraud_assessment_review
    ON fraud.fraud_assessments (
                                review_status
        );

CREATE INDEX idx_fraud_assessment_model
    ON fraud.fraud_assessments (
                                model_version
        );

CREATE INDEX idx_fraud_assessment_time
    ON fraud.fraud_assessments (
                                assessed_at
        );

CREATE INDEX idx_fraud_assessment_queue
    ON fraud.fraud_assessments (
                                review_status,
                                risk_level,
                                assessed_at
        );

CREATE INDEX idx_fraud_assessment_supplier_time
    ON fraud.fraud_assessments (
                                supplier_id,
                                assessed_at
        );