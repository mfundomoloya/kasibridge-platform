

CREATE FUNCTION public.prevent_procurement_audit_mutation() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    RAISE EXCEPTION
        'Procurement audit events are append-only. % is not permitted.',
        TG_OP
        USING ERRCODE = '55000';
END;
$$;

