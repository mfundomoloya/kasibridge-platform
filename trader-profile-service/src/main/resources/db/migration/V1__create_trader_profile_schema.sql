CREATE TABLE trader_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    user_id BIGINT NOT NULL,

    full_name VARCHAR(150) NOT NULL,

    phone_number VARCHAR(20) NOT NULL,

    email VARCHAR(254),

    business_name VARCHAR(200) NOT NULL,

    business_type VARCHAR(100),

    trading_area VARCHAR(150),

    business_description VARCHAR(1000),

    id_number VARCHAR(13),

    has_business_registration BOOLEAN,

    cipc_number VARCHAR(50),

    has_bank_account BOOLEAN,

    bank_name VARCHAR(100),

    onboarding_channel VARCHAR(20),

    status VARCHAR(20) NOT NULL,

    created_at TIMESTAMP(6) WITHOUT TIME ZONE
        NOT NULL,

    updated_at TIMESTAMP(6) WITHOUT TIME ZONE
        NOT NULL,

    CONSTRAINT uk_trader_profiles_user_id
        UNIQUE (user_id),

    CONSTRAINT uk_trader_profiles_phone_number
        UNIQUE (phone_number),

    CONSTRAINT uk_trader_profiles_email
        UNIQUE (email),

    CONSTRAINT ck_trader_profiles_onboarding_channel
        CHECK (
            onboarding_channel IN (
                'WEB',
                'WHATSAPP'
            )
        ),

    CONSTRAINT ck_trader_profiles_status
        CHECK (
            status IN (
                'PENDING',
                'ACTIVE',
                'SUSPENDED',
                'INACTIVE'
            )
        )
);
